import { NextResponse } from "next/server";
import type { EmailOtpType } from "@supabase/supabase-js";
import { createClient } from "@/lib/supabase/server";

// Redirect target for invite/confirmation email links. Two distinct link
// shapes land here depending on flow:
//  - OAuth/PKCE: `?code=...` -> exchangeCodeForSession
//  - Email OTP (invite/recovery/magiclink/signup, i.e. our generateLink()
//    invite emails): `?token_hash=...&type=...` -> verifyOtp
// Then forwards to `next` (defaults to "/" — role-based routing happens
// client-side once the profile loads).
export async function GET(request: Request) {
  const { searchParams, origin } = new URL(request.url);
  const code = searchParams.get("code");
  const tokenHash = searchParams.get("token_hash");
  const type = searchParams.get("type") as EmailOtpType | null;
  const next = searchParams.get("next") ?? "/";

  const supabase = await createClient();

  if (code) {
    const { error } = await supabase.auth.exchangeCodeForSession(code);
    if (!error) {
      return NextResponse.redirect(`${origin}${next}`);
    }
  } else if (tokenHash && type) {
    const { error } = await supabase.auth.verifyOtp({ type, token_hash: tokenHash });
    if (!error) {
      return NextResponse.redirect(`${origin}${next}`);
    }
  }

  return NextResponse.redirect(`${origin}/login?error=auth_callback_failed`);
}
